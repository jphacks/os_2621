/**
 * カタカナをひらがなに変換するヘルパー関数
 */
export function katakanaToHiragana(text: string): string {
  return text.replace(/[\u30a1-\u30f6]/g, (match) => {
    const code = match.charCodeAt(0) - 0x60;
    return String.fromCharCode(code);
  });
}

/**
 * 照合用のテキスト正規化関数
 * - NFKC正規化（全角英数・半角カナ等の統一）
 * - 英字の小文字化
 * - カタカナをひらがなへ統一
 * - ゼロ幅スペースや制御文字、空白・記号・絵文字による分断を除去した文字列も生成可能にする
 */
export function normalizeForCrisisCheck(text: string): {
  normalized: string;
  compact: string;
} {
  // 1. NFKC正規化 & 小文字化
  const nfkc = text.normalize("NFKC").toLowerCase();
  // 2. カタカナをひらがなに統一（「シニタイ」「リスカ」等もひらがなで一貫判定できるようにする）
  const hira = katakanaToHiragana(nfkc);
  // 3. 空白・記号・絵文字などを挟んだ回避（「し に た い」「死😭に😭た😭い」等）に対応するコンパクト版
  // ひらがな・漢字・英数字のみを残す
  const compact = hira.replace(
    /[^\p{Script=Hiragana}\p{Script=Han}a-z0-9ー]/gu,
    ""
  );

  return {
    normalized: hira,
    compact,
  };
}

